fn is_word_boundary(text: &str, at: usize) -> bool {
    text[..at]
        .chars()
        .next_back()
        .map(|c| !(c.is_ascii_alphanumeric() || c == '_'))
        .unwrap_or(true)
}

/// Shannon entropy in bits per character.
pub fn entropy(s: &str) -> f64 {
    let mut counts: std::collections::BTreeMap<char, f64> = std::collections::BTreeMap::new();
    let mut n: f64 = 0.0;
    for c in s.chars() {
        *counts.entry(c).or_insert(0.0) += 1.0;
        n += 1.0;
    }
    if n == 0.0 {
        return 0.0;
    }
    -counts
        .values()
        .map(|c| (c / n) * (c / n).log2())
        .sum::<f64>()
}

fn all_hex(s: &str) -> bool {
    !s.is_empty() && s.chars().all(|c| c.is_ascii_hexdigit())
}

/// UUIDs and plain hash digests are identifiers, not secrets, unless a keyword sits next to them.
fn identifier_shape(s: &str) -> bool {
    let uuid = s.len() == 36
        && s.chars().enumerate().all(|(i, c)| {
            if matches!(i, 8 | 13 | 18 | 23) {
                c == '-'
            } else {
                c.is_ascii_hexdigit()
            }
        });
    uuid || (matches!(s.len(), 32 | 40 | 56 | 64 | 96 | 128) && all_hex(s))
        || s.starts_with("sha256-")
        || s.starts_with("sha512-")
        || s.starts_with("sha384-")
}

fn templated(v: &str) -> bool {
    let v = v.trim();
    v.starts_with("${")
        || v.starts_with("{{")
        || v.starts_with('<')
        || v.starts_with('$')
        || v.starts_with('%')
        || v.starts_with('{')
        || v.starts_with('[')
        || (v.starts_with("${") && v.ends_with('}'))
        || v.contains("{{")
        || v.contains("${")
        || v.ends_with('%')
}

fn indirect_reference(v: &str) -> bool {
    v.contains('(')
        || v.contains(')')
        || v.contains("os.environ")
        || v.contains("getenv")
        || v.contains("process.env")
        || v.contains("::")
        || v.contains("[\"")
        || v.contains("['")
        || v.contains("->")
        || v.starts_with("self.")
        || v.starts_with("this.")
        || v.starts_with("++")
        || v.starts_with("--")
        || v.starts_with("!")
}

