//! One secret detector for the whole product. The importer decides what an agent may read, memory refuses to store
//! secrets, and the release check is the last line before anything leaves the computer. They used to carry three
//! disagreeing lists; they now share this table.
//!
//! The provider formats follow the public token layouts that the MIT-licensed gitleaks rule set also covers (prefix,
//! alphabet and length); the matcher, the false-positive filters and the wallet rules are written here. See NOTICE.md.

pub mod pii;

use std::collections::BTreeSet;

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Hit {
    pub rule: &'static str,
    /// Byte offsets into the scanned text. Decoded hits point at the encoded segment.
    pub start: usize,
    pub end: usize,
    pub decoded: bool,
}

const B64: &str = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/=_-";

struct Format {
    rule: &'static str,
    prefix: &'static str,
    /// Allowed characters of the body after the prefix.
    body: Body,
    min: usize,
    max: usize,
}

#[derive(Clone, Copy)]
enum Body {
    Alnum,
    AlnumDashUnderscore,
    AlnumDashUnderscoreDot,
    Hex,
    UpperBase32,
    Base58,
    SlackLike,
    Base64Std,
    Base64Any,
    UpperAlnumDash,
    Bech32Upper,
    HexUnderscore,
    UrlPath,
    UpperAlnum,
    LowerAlnum,
    AlnumDot,
    WordEqDotDash,
}

/// The provider formats as a JavaScript module, so the browser extension checks the same table before anything leaves
/// the page. A test keeps `apps/extension/formats.js` identical to this output.
pub fn formats_js() -> String {
    let mut out = String::from("// Generated by `cargo run -p kk-secrets --example export_formats`. Do not edit.\nexport const FORMATS = [\n");
    for f in FORMATS {
        let body = match f.body {
            Body::Alnum => "alnum",
            Body::AlnumDashUnderscore => "alnum-dash-underscore",
            Body::AlnumDashUnderscoreDot => "alnum-dash-underscore-dot",
            Body::Hex => "hex",
            Body::UpperBase32 => "upper-base32",
            Body::Base58 => "base58",
            Body::SlackLike => "slack-like",
            Body::Base64Std => "base64-std",
            Body::Base64Any => "base64-any",
            Body::UpperAlnumDash => "upper-alnum-dash",
            Body::Bech32Upper => "bech32-upper",
            Body::HexUnderscore => "hex-underscore",
            Body::UrlPath => "url-path",
            Body::UpperAlnum => "upper-alnum",
            Body::LowerAlnum => "lower-alnum",
            Body::AlnumDot => "alnum-dot",
            Body::WordEqDotDash => "word-eq-dot-dash",
        };
        out.push_str(&format!(
            "  {{ rule: {:?}, prefix: {:?}, body: {:?}, min: {}, max: {} }},\n",
            f.rule, f.prefix, body, f.min, f.max
        ));
    }
    out.push_str("];\nexport const PRIVATE_KEY_BLOCKS = [\n");
    for m in PRIVATE_KEY_BLOCKS {
        out.push_str(&format!("  {m:?},\n"));
    }
    out.push_str("];\n");
    out
}

/// One provider format as plain data, for tests and tools that need to build or check tokens.
#[derive(Debug, Clone)]
pub struct FormatSpec {
    pub rule: &'static str,
    pub prefix: &'static str,
    pub min: usize,
    pub max: usize,
    /// Every printable ASCII character the body may contain.
    pub alphabet: String,
}

pub fn format_specs() -> Vec<FormatSpec> {
    FORMATS
        .iter()
        .map(|f| FormatSpec {
            rule: f.rule,
            prefix: f.prefix,
            min: f.min,
            max: f.max,
            alphabet: (0x20u8..0x7f)
                .map(char::from)
                .filter(|c| body_ok(f.body, *c))
                .collect(),
        })
        .collect()
}

fn body_ok(b: Body, c: char) -> bool {
    match b {
        Body::Alnum => c.is_ascii_alphanumeric(),
        Body::AlnumDashUnderscore => c.is_ascii_alphanumeric() || c == '-' || c == '_',
        Body::AlnumDashUnderscoreDot => {
            c.is_ascii_alphanumeric() || c == '-' || c == '_' || c == '.'
        }
        Body::Hex => c.is_ascii_hexdigit(),
        Body::UpperBase32 => c.is_ascii_uppercase() || ('2'..='7').contains(&c),
        Body::Base58 => c.is_ascii_alphanumeric() && !matches!(c, '0' | 'O' | 'I' | 'l'),
        Body::SlackLike => c.is_ascii_alphanumeric() || c == '-',
        Body::Base64Std => c.is_ascii_alphanumeric() || c == '+' || c == '/',
        Body::Base64Any => c.is_ascii_alphanumeric() || matches!(c, '+' | '/' | '=' | '_' | '-'),
        Body::UpperAlnumDash => c.is_ascii_uppercase() || c.is_ascii_digit() || c == '-',
        Body::Bech32Upper => "QPZRY9X8GF2TVDW0S3JN54KHCE6MUA7L".contains(c),
        Body::HexUnderscore => c.is_ascii_hexdigit() || c == '_',
        Body::UrlPath => c.is_ascii_alphanumeric() || matches!(c, '-' | '@' | '/'),
        Body::UpperAlnum => c.is_ascii_uppercase() || c.is_ascii_digit(),
        Body::LowerAlnum => c.is_ascii_lowercase() || c.is_ascii_digit(),
        Body::AlnumDot => c.is_ascii_alphanumeric() || c == '.',
        Body::WordEqDotDash => c.is_ascii_alphanumeric() || matches!(c, '_' | '=' | '.' | '-'),
    }
}

