fn sequential(v: &str) -> bool {
    let b: Vec<u8> = v.bytes().collect();
    if b.len() < 6 {
        return false;
    }
    if b.windows(2).all(|w| w[1] == w[0] + 1) || b.windows(2).all(|w| w[1] == w[0]) {
        return true;
    }
    let upper = v.to_ascii_uppercase();
    SEQUENCES.iter().any(|seq| seq.contains(&upper))
}

fn strip_quotes(v: &str) -> &str {
    v.trim()
        .trim_matches(|c| c == '"' || c == '\'' || c == '`' || c == ',' || c == ';')
}

/// A value that plausibly is a literal credential: long enough, no whitespace, not a reference, not a placeholder, and
/// either random enough or mixing letters with digits.
pub fn credential_value(raw: &str) -> bool {
    credential_value_with(raw, false)
}

/// `allow_identifier` is set when a key name such as `api_token` or `secret` sits directly in front of the value: then a
/// UUID or a hash-length hex string is a credential, not an identifier (an Algolia key is 32 hex characters).
fn credential_value_with(raw: &str, allow_identifier: bool) -> bool {
    let v = strip_quotes(raw);
    if v.len() < 8
        || v.contains(char::is_whitespace)
        || templated(v)
        || indirect_reference(v)
        || placeholder(v)
        || sequential(v)
    {
        return false;
    }
    if !allow_identifier && identifier_shape(v) {
        return false;
    }
    let has_digit = v.chars().any(|c| c.is_ascii_digit());
    let has_alpha = v.chars().any(|c| c.is_ascii_alphabetic());
    let has_special = v.chars().any(|c| !c.is_ascii_alphanumeric());
    let all_lower_alpha = v.chars().all(|c| c.is_ascii_lowercase());
    // A plain word is not a credential, but a long run of letters after a password keyword is a passphrase.
    if all_lower_alpha || v.chars().all(|c| c.is_ascii_uppercase()) {
        return (v.len() >= 16 && entropy(v) >= 3.4) || (v.len() >= 20 && entropy(v) >= 3.1);
    }
    // Readable words with a dash or a mixed-case run are not credentials; a credential has digits or very high entropy.
    if !has_digit {
        return v.len() >= 20 && entropy(v) >= 4.0 && has_alpha;
    }
    entropy(v) >= 2.5 && has_alpha || (has_special && entropy(v) >= 3.0)
}

/// A provider-shaped value whose body is a fill character or says what it is (`ghp_xxxx...`, `..._PUT_YOUR_TOKEN_HERE_...`)
/// is documentation, not a credential. Real bodies are random, so they use many distinct characters and never spell these words.
pub fn placeholder_body(body: &str) -> bool {
    let distinct: BTreeSet<char> = body.chars().collect();
    if body.chars().count() >= 12 && distinct.len() <= 3 {
        return true;
    }
    let l = body.to_ascii_lowercase();
    body.len() >= 16
        && [
            "your",
            "example",
            "placeholder",
            "changeme",
            "dummy",
            "redacted",
            "token_here",
            "key_here",
        ]
        .iter()
        .any(|w| l.contains(w))
}

fn push(hits: &mut Vec<Hit>, rule: &'static str, start: usize, end: usize, decoded: bool) {
    hits.push(Hit {
        rule,
        start,
        end,
        decoded,
    });
}

/// Which formats can start with a given byte, so the text is walked once instead of once per format.
fn format_index() -> &'static Vec<Vec<usize>> {
    static INDEX: std::sync::OnceLock<Vec<Vec<usize>>> = std::sync::OnceLock::new();
    INDEX.get_or_init(|| {
        let mut idx: Vec<Vec<usize>> = vec![Vec::new(); 256];
        for (i, f) in FORMATS.iter().enumerate() {
            idx[f.prefix.as_bytes()[0] as usize].push(i);
        }
        idx
    })
}

fn scan_formats(text: &str, decoded: bool, hits: &mut Vec<Hit>) {
    let index = format_index();
    for (start, byte) in text.bytes().enumerate() {
        let candidates = &index[byte as usize];
        if candidates.is_empty() {
            continue;
        }
        for &fi in candidates {
            let f = &FORMATS[fi];
            // every prefix starts with an ASCII byte, so `start` is always on a character boundary
            if !text[start..].starts_with(f.prefix) {
                continue;
            }
            let from = start + f.prefix.len();
            if !is_word_boundary(text, start) {
                continue;
            }
            let body: String = text[from..]
                .chars()
                .take_while(|c| body_ok(f.body, *c))
                .collect();
            let n = body.chars().count();
            let documented_example = f.rule == "aws access key id" && body.contains("EXAMPLE");
            if n >= f.min
                && n <= f.max.max(f.min)
                && !documented_example
                && !placeholder_body(&body)
            {
                if f.prefix == "SK"
                    && !(body.chars().any(|c| c.is_ascii_digit())
                        && body.chars().any(|c| c.is_ascii_alphabetic()))
                {
                    continue;
                }
                push(hits, f.rule, start, from + body.len(), decoded);
            }
        }
    }
}

fn scan_blocks_and_urls(text: &str, decoded: bool, hits: &mut Vec<Hit>) {
    for m in PRIVATE_KEY_BLOCKS {
        if let Some(i) = text.find(m) {
            push(hits, "private key block", i, i + m.len(), decoded);
        }
    }
    // JWT: three dot-separated base64url parts, the first two starting with eyJ
    let mut pos = 0;
    for w in text.split(|c: char| !(c.is_ascii_alphanumeric() || matches!(c, '.' | '_' | '-'))) {
        let start = text[pos..].find(w).map(|o| pos + o).unwrap_or(pos);
        pos = start + w.len();
        let parts: Vec<&str> = w.split('.').collect();
        if parts.len() == 3 && w.starts_with("eyJ") && parts[1].starts_with("eyJ") && w.len() >= 30
        {
            push(hits, "signed token", start, start + w.len(), decoded);
        }
    }
    // credentials inside a URL: scheme://user:password@host
    let mut at = 0;
    while let Some(i) = text[at..].find("://") {
        let auth_start = at + i + 3;
        let rest = &text[auth_start..];
        let authority: &str = rest
            .split(|c: char| {
                c == '/' || c == '?' || c == '#' || c.is_whitespace() || c == '"' || c == '\''
            })
            .next()
            .unwrap_or("");
        if let Some((userinfo, _)) = authority.rsplit_once('@') {
            if let Some((_, pw)) = userinfo.split_once(':') {
                let pw_l = pw.to_ascii_lowercase();
                let example_host = authority.to_ascii_lowercase().contains("example")
                    || authority.contains("localhost");
                if !pw.is_empty()
                    && !templated(pw)
                    && !placeholder(pw)
                    && !example_host
                    && ![
                        "pass",
                        "password",
                        "passwd",
                        "secret",
                        "token",
                        "pwd",
                        "xxx",
                        "xxxx",
                        "****",
                        "changeme",
                        "your-password",
                        "yourpassword",
                    ]
                    .contains(&pw_l.as_str())
                {
                    push(
                        hits,
                        "password in a URL",
                        auth_start,
                        auth_start + authority.len(),
                        decoded,
                    );
                }
            }
        }
        at = auth_start;
    }
}

/// The value after an assignment: the content of a quoted string, or an unquoted run that stops at whitespace and at
/// the punctuation that ends a value in code, query strings and lists.
fn take_value(v: &str) -> (&str, bool) {
    let mut chars = v.char_indices();
    match chars.next() {
        Some((_, q @ ('"' | '\'' | '`'))) => {
            let rest = &v[1..];
            match rest.find(q) {
                Some(end) => (&rest[..end], true),
                None => (rest.split_whitespace().next().unwrap_or(""), true),
            }
        }
        _ => {
            let end = v
                .find(|c: char| {
                    c.is_whitespace() || matches!(c, ',' | ';' | '&' | ')' | '}' | ']' | '>')
                })
                .unwrap_or(v.len());
            // a JSON string holding several lines shows each break as the two characters backslash and n
            let escaped = ["\\n", "\\r", "\\t"].iter().filter_map(|e| v.find(e)).min();
            (&v[..end.min(escaped.unwrap_or(end))], false)
        }
    }
}

/// A path that begins with names: its first one or two segments read as names (lower-case words with dashes or underscores, or
/// CamelCase words, each with at most eight digits at the end), as in `/home/deploy/...` or `/srv/Backup20240131/...`. The
/// segments of a random key are not names, whatever slashes the key happens to hold; what comes after the first two segments
/// of a real path (an id, a timestamp) can look like anything.
fn wordy_path(v: &str) -> bool {
    let name = |seg: &str| {
        let body = seg.trim_end_matches(|c: char| c.is_ascii_digit());
        let digits = seg.len() - body.len();
        digits <= 8
            && !body.is_empty()
            && (body
                .chars()
                .all(|c| c.is_ascii_lowercase() || matches!(c, '-' | '_'))
                || camel_words_counting(body, 0, 1))
    };
    let first: Vec<&str> = v.split('/').filter(|s| !s.is_empty()).take(2).collect();
    !first.is_empty() && first.iter().all(|s| name(s))
}

/// A CamelCase or camelCase identifier made of words: `MyPasswordField`, `getAccessToken2`. Every capital letter starts a
/// word of at least two letters (a capital followed by lower-case letters), and at most two digits close the name. A
/// random mix of letters and digits such as `YqSYcZaiM9aIjsnGIS5X` has capitals in a row, one-letter pieces and digits in the
/// middle, so it is not taken for a name, and a value that long after `password:` is read as the password it is.
fn camel_identifier(v: &str) -> bool {
    if !v.chars().all(|c| c.is_ascii_alphanumeric())
        || !v.chars().next().is_some_and(|c| c.is_ascii_alphabetic())
    {
        return false;
    }
    let digits = v.chars().filter(|c| c.is_ascii_digit()).count();
    let mut body = v.trim_end_matches(|c: char| c.is_ascii_digit());
    if digits > 2 || v.len() - body.len() != digits || body.is_empty() {
        return false;
    }
    // a numeric type name: `AtomicU64`, `Vec3`-style endings made of one capital and digits count as a word
    let mut extra = 0usize;
    if digits > 0 {
        let mut it = body.chars().rev();
        if let (Some(last), Some(before)) = (it.next(), it.next()) {
            if last.is_ascii_uppercase() && before.is_ascii_lowercase() {
                body = &body[..body.len() - 1];
                extra = 1;
            }
        }
    }
    camel_words_counting(body, extra, 2)
}

/// Whether letters make at least `min` words, each a capital (or the start of a camelCase name) and lower-case letters, two
/// letters or more; `extra` words were already counted.
fn camel_words_counting(body: &str, extra: usize, min: usize) -> bool {
    let chars: Vec<char> = body.chars().collect();
    let mut words = extra;
    let mut i = 0usize;
    while i < chars.len() {
        let start = i;
        if chars[i].is_ascii_uppercase() {
            i += 1;
        }
        let lower_from = i;
        while i < chars.len() && chars[i].is_ascii_lowercase() {
            i += 1;
        }
        if i == lower_from || i - start < 2 {
            return false;
        }
        words += 1;
    }
    words >= min
}

/// Code is full of `token = point.tokens`, `secret: Optional[str]` and `"test-key"`. An unquoted value is a literal only if
/// it has no code syntax; a quoted one must not be a placeholder word, a test marker or plain readable words.
fn literal_credential(v: &str, quoted: bool, allow_identifier: bool) -> bool {
    if !v.is_ascii() {
        return false;
    }
    let lower = v.to_ascii_lowercase();
    // A long run of random-looking characters is a token, whatever it spells by chance: a marker word ("test", "demo") inside
    // it, or a slash or two (the alphabet of an AWS secret key includes `/` and `+`), does not make it a fixture or a path.
    let random_token = v.len() >= 24
        && !v.contains('.')
        && v.chars()
            .all(|c| c.is_ascii_alphanumeric() || matches!(c, '+' | '/' | '='))
        && v.chars().any(|c| c.is_ascii_lowercase())
        && v.chars().any(|c| c.is_ascii_uppercase())
        && v.chars().any(|c| c.is_ascii_digit())
        && entropy(v) >= 4.2
        && !wordy_path(v);
    // A word that says what the value is ("example", "placeholder", "redacted") is never chance, so it always counts. The
    // four-letter ones can turn up inside a random token by chance, so a value shaped like a token is not dropped for them.
    let says_so = [
        "dummy",
        "example",
        "sample",
        "placeholder",
        "changeme",
        "redacted",
        "xxxx",
        "lorem",
        "default",
    ]
    .iter()
    .any(|m| lower.contains(m));
    let maybe_chance = ["test", "mock", "fake", "demo"]
        .iter()
        .any(|m| lower.contains(m));
    if (says_so || (maybe_chance && !random_token)) && v.len() < 48 {
        return false;
    }
    // readable identifiers: lowercase words joined by dashes or underscores, no digits
    if v.len() < 48
        && v.chars()
            .all(|c| c.is_ascii_lowercase() || c == '-' || c == '_' || c == '.')
        && v.chars().any(|c| matches!(c, '-' | '_' | '.'))
    {
        return false;
    }
    // environment variable names, CamelCase identifiers and paths are names, not values
    let env_name = v.len() >= 3
        && v.chars().next().is_some_and(|c| c.is_ascii_uppercase())
        && v.chars()
            .all(|c| c.is_ascii_uppercase() || c.is_ascii_digit() || c == '_');
    let camel = camel_identifier(v);
    let path_like = !random_token
        && (v.starts_with('/')
            || v.starts_with("./")
            || v.starts_with("~/")
            || (v.contains('/')
                && !v.contains('=')
                && !v.contains('+')
                && v.split('/').filter(|p| !p.is_empty()).count() >= 2
                && v.chars().filter(|c| *c == '/').count() >= 2));
    if env_name || camel || path_like {
        return false;
    }
    if !quoted {
        let code_syntax = v.contains(['(', ')', '[', ']', '{', '}', '<', '>', '`', '\\', '?'])
            || v.contains("::")
            || v.contains("->")
            || v.contains("=>");
        let member_path = v.contains('.')
            && (v.len() < 32 || !v.chars().any(|c| c.is_ascii_digit()))
            && v.split('.').all(|p| {
                !p.is_empty()
                    && p.chars()
                        .next()
                        .is_some_and(|c| c.is_ascii_alphabetic() || c == '_')
                    && p.chars().all(|c| c.is_ascii_alphanumeric() || c == '_')
            });
        if code_syntax || member_path {
            return false;
        }
    }
    credential_value_with(v, allow_identifier)
}

/// A bare `...Key = value` is a credential only when the value is clearly one: 20 or more token characters with high
/// entropy, or a UUID. Version strings, identifiers with dots and short codes are left alone.
fn key_value_strong(v: &str) -> bool {
    let v = strip_quotes(v);
    let uuid = v.len() == 36
        && v.chars().enumerate().all(|(i, c)| {
            if matches!(i, 8 | 13 | 18 | 23) {
                c == '-'
            } else {
                c.is_ascii_hexdigit()
            }
        });
    uuid || (v.len() >= 20
        && v.chars()
            .all(|c| c.is_ascii_alphanumeric() || matches!(c, '_' | '-' | '+' | '/' | '='))
        && entropy(v) >= 3.3)
}

/// How the value was introduced; the weaker forms are accepted only for stronger values.
#[derive(Clone, Copy, PartialEq, Eq)]
enum Form {
    Plain,
    /// `("API_TOKEN", "value")`: a call or tuple, where lists of names look the same.
    Comma,
    /// `password == "value"`: a credential written into a check.
    Compare,
}

/// What follows the operator of an assignment. Besides `=` and `:`, the make-style `:=`, `::=`, `:::=` and `?=`, PHP's
/// `.=`, the arrow `=>` and the call form `("KEY", "value")` all introduce a value; a comma only does when a quoted
/// string follows it, so `token, secret` in a list is not an assignment. A type word between the name and the `=`
/// (`var token string = "..."`) is skipped.
fn after_operator(rest: &str) -> Option<(&str, Form)> {
    for op in ["!==", "===", "!=", "=="] {
        if let Some(v) = rest.strip_prefix(op) {
            return Some((v, Form::Compare));
        }
    }
    for op in [":::=", "::=", ":=", "?=", ".=", "=>", "="] {
        if let Some(v) = rest.strip_prefix(op) {
            return Some((v, Form::Plain));
        }
    }
    if let Some(v) = rest.strip_prefix(':') {
        // `token: string = "..."` carries a type between the colon and the value
        return Some((skip_type_to_value(v).unwrap_or(v), Form::Plain));
    }
    if let Some(v) = skip_type_to_value(rest) {
        // `var token string = "..."`
        return Some((v, Form::Plain));
    }
    if let Some(v) = rest.strip_prefix(',') {
        if v.trim_start().starts_with(['"', '\'', '`']) {
            return Some((v, Form::Comma));
        }
    }
    rest.strip_prefix("is ")
        .or_else(|| rest.strip_prefix("was "))
        .map(|v| (v, Form::Plain))
}

/// Readable names with a number on the end (`gateway-api-key-1234567890`, `old-secret-123`): lowercase words and digit
/// groups joined by `-`, `_` or `.`. Credentials are not written like that, fixtures and examples are.
fn word_slug(v: &str) -> bool {
    let parts: Vec<&str> = v.split(['-', '_', '.']).collect();
    parts.len() >= 2
        && parts.iter().all(|p| {
            !p.is_empty()
                && ((p.len() <= 14 && p.chars().all(|c| c.is_ascii_digit()))
                    || (p.len() <= 5
                        && p.starts_with('v')
                        && p.len() > 1
                        && p[1..].chars().all(|c| c.is_ascii_digit()))
                    || (p.len() <= 14
                        && p.chars().all(|c| c.is_ascii_lowercase())
                        && p.chars().any(|c| "aeiouy".contains(c))))
        })
        && parts
            .iter()
            .any(|p| p.chars().any(|c| c.is_ascii_lowercase()))
}

/// Type names that can sit between a name and its value (`var token string = "..."`). Any other word there is prose or
/// markup (`api_key id=ef56gh78`, `Discord" src="https://...`), not a declaration.
const TYPE_WORDS: &[&str] = &[
    "string",
    "str",
    "text",
    "char",
    "chars",
    "any",
    "object",
    "bytes",
    "nsstring",
    "securestring",
    "optional",
    "option",
    "cstring",
];

/// `string = value` or `Optional<String> := value`: one type word, then an assignment.
fn skip_type_to_value(s: &str) -> Option<&str> {
    let t = s.trim_start().trim_start_matches(['&', '*']);
    let end = t
        .find(|c: char| {
            !(c.is_ascii_alphanumeric() || matches!(c, '_' | '<' | '>' | '[' | ']' | '.' | '?'))
        })
        .unwrap_or(t.len());
    if end == 0 || end > 32 {
        return None;
    }
    let word = t[..end].split(['<', '[']).next().unwrap_or("");
    if !TYPE_WORDS.contains(&word.to_ascii_lowercase().as_str()) {
        return None;
    }
    let after = t[end..].trim_start();
    if after.starts_with("==") || after.starts_with("=>") {
        return None;
    }
    after.strip_prefix(":=").or_else(|| after.strip_prefix('='))
}

/// The rest of a key name in one comparable form: camelCase and `.` or `-` become `_` boundaries, so `credentialId`,
/// `credentials.url` and `token-count` are tested like `credential_id`, `credentials_url` and `token_count`.
fn suffix_form(rest: &str) -> String {
    let mut out = String::new();
    // the rest of a name starts where the keyword ended, so a capital right away begins a new word (`credentialId`)
    let mut prev_lower = true;
    for c in rest.chars() {
        if c.is_ascii_uppercase() && prev_lower {
            out.push('_');
        }
        out.push(match c {
            '.' | '-' => '_',
            c => c.to_ascii_lowercase(),
        });
        prev_lower = c.is_ascii_lowercase() || c.is_ascii_digit();
    }
    out
}

/// No real key name is longer than this. Reading further would make every incidental match inside a long run of
/// letters (a base64 blob) walk the whole run.
const MAX_KEY_NAME: usize = 80;

/// Every word that can name a credential: the general keywords, the provider names, and the bare `key` that counts only
/// as the tail of a longer name. The position in this list identifies the word.
fn credential_words() -> &'static Vec<&'static str> {
    static WORDS: std::sync::OnceLock<Vec<&'static str>> = std::sync::OnceLock::new();
    WORDS.get_or_init(|| {
        KEYWORDS
            .iter()
            .chain(PROVIDERS.iter())
            .chain(std::iter::once(&"key"))
            .copied()
            .collect()
    })
}

/// Where each credential word occurs in a lowercased line, found in one pass over the line.
fn keyword_occurrences(lower: &str) -> Vec<Vec<usize>> {
    static BY_FIRST_BYTE: std::sync::OnceLock<Vec<Vec<usize>>> = std::sync::OnceLock::new();
    let words = credential_words();
    let index = BY_FIRST_BYTE.get_or_init(|| {
        let mut idx: Vec<Vec<usize>> = vec![Vec::new(); 256];
        for (i, w) in words.iter().enumerate() {
            idx[w.as_bytes()[0] as usize].push(i);
        }
        idx
    });
    let mut out: Vec<Vec<usize>> = vec![Vec::new(); words.len()];
    let bytes = lower.as_bytes();
    for (i, &b) in bytes.iter().enumerate() {
        for &wi in &index[b as usize] {
            if bytes[i..].starts_with(words[wi].as_bytes()) {
                out[wi].push(i);
            }
        }
    }
    out
}

fn scan_assignments(text: &str, decoded: bool, hits: &mut Vec<Hit>) {
    scan_bare_key(text, decoded, hits);
    let mut offset = 0;
    let all: Vec<&str> = text.split_inclusive('\n').collect();
    for (li, line) in all.iter().copied().enumerate() {
        let l = line.trim_end_matches(['\n', '\r']);
        {
            let lower = l.to_ascii_lowercase();
            let occurrences = keyword_occurrences(&lower);
            for (ki, kw) in credential_words().iter().enumerate() {
                if occurrences[ki].is_empty() {
                    continue;
                }
                let is_provider = ki >= KEYWORDS.len() && ki < KEYWORDS.len() + PROVIDERS.len();
                let is_key_suffix = ki == KEYWORDS.len() + PROVIDERS.len();
                let mut from = 0;
                while let Some(kstart) = {
                    let occ = &occurrences[ki];
                    occ.get(occ.partition_point(|&o| o < from)).copied()
                } {
                    if is_provider || is_key_suffix {
                        // the name must begin a word of the key: after a separator, at the start, or at a camelCase step
                        let lb = l.as_bytes();
                        let boundary = kstart == 0
                            || !lb[kstart - 1].is_ascii_alphanumeric()
                            || (lb[kstart - 1].is_ascii_lowercase()
                                && lb[kstart].is_ascii_uppercase());
                        let inside_value = kstart > 0 && matches!(lb[kstart - 1], b':' | b'/');
                        if is_provider && (!boundary || inside_value) {
                            from = kstart + kw.len();
                            continue;
                        }
                        // `key` counts only as the tail of a longer name (`HEROKU_KEY`, `serviceKey`), never alone or as a prefix
                        let separated = kstart > 0
                            && (matches!(lb[kstart - 1], b'_' | b'-' | b'.')
                                || (lb[kstart - 1].is_ascii_lowercase()
                                    && lb[kstart].is_ascii_uppercase()));
                        if is_key_suffix && !separated {
                            from = kstart + kw.len();
                            continue;
                        }
                    }
                    let after = &l[kstart + kw.len()..];
                    from = kstart + kw.len();
                    // the key name may continue (PASSWORD_FILE, token_count): take the rest of the identifier
                    let ident_rest: String = after
                        .chars()
                        .take_while(|c| {
                            c.is_ascii_alphanumeric() || *c == '_' || *c == '-' || *c == '.'
                        })
                        .take(MAX_KEY_NAME)
                        .collect();
                    let lower_rest = suffix_form(&ident_rest);
                    let key_name = {
                        let before: String = l[..kstart]
                            .chars()
                            .rev()
                            .take_while(|c| {
                                c.is_ascii_alphanumeric() || matches!(c, '_' | '-' | '.')
                            })
                            .take(MAX_KEY_NAME)
                            .collect::<Vec<_>>()
                            .into_iter()
                            .rev()
                            .collect();
                        format!("{before}{kw}{ident_rest}")
                    };
                    let env_style =
                        key_name.contains('_') || !key_name.chars().any(|c| c.is_ascii_lowercase());
                    let key_name = key_name.to_ascii_lowercase();
                    let hash_named = [
                        "hash",
                        "sha",
                        "md5",
                        "digest",
                        "checksum",
                        "etag",
                        "fingerprint",
                        "commit",
                        "revision",
                        "uuid",
                        "guid",
                    ]
                    .iter()
                    .any(|w| key_name.contains(w));
                    let password_class = [
                        "password",
                        "passwd",
                        "pwd",
                        "passphrase",
                        "contrasena",
                        "contraseña",
                        "db_pass",
                        "database_pass",
                        "key_pass",
                    ]
                    .iter()
                    .any(|w| key_name.contains(w));
                    // everything a value must satisfy to count, given how it was introduced
                    let accept = |tok: &str, quoted: bool, form: Form| -> bool {
                        literal_credential(tok, quoted, !hash_named)
                            && (!is_key_suffix || key_value_strong(tok))
                            && (password_class || !word_slug(tok))
                            && match form {
                                Form::Plain => true,
                                Form::Comma => env_style && tok.chars().any(|c| c.is_ascii_digit()),
                                Form::Compare => tok.len() >= 10,
                            }
                    };
                    if is_key_suffix
                        && (NOT_A_CREDENTIAL_KEY.iter().any(|w| key_name.contains(w))
                            || ident_rest
                                .chars()
                                .next()
                                .is_some_and(|c| c.is_ascii_alphanumeric()))
                    {
                        // `key` followed by more letters (`keyboard`, `keyword`, `key_file` is caught below) is not a credential name
                        continue;
                    }
                    if [
                        "_file",
                        "_path",
                        "_url",
                        "_count",
                        "_len",
                        "_length",
                        "_name",
                        "_type",
                        "_ttl",
                        "_expiry",
                        "_expires",
                        "_endpoint",
                        "_header",
                        "_field",
                        "_id",
                        "_input",
                        "_output",
                        "_budget",
                        "_limit",
                        "_usage",
                        "s",
                    ]
                    .iter()
                    .any(|s| lower_rest == *s || lower_rest.starts_with(&format!("{s}_")))
                        && !lower_rest.is_empty()
                        && lower_rest != "s"
                    {
                        continue;
                    }
                    if !lower_rest.is_empty()
                        && NOT_SECRET_SUFFIXES.iter().any(|s| lower_rest.ends_with(s))
                    {
                        continue;
                    }
                    // `"literal" == password`: the same hard-coded check written the other way round
                    {
                        let before_len = l[..kstart]
                            .chars()
                            .rev()
                            .take_while(|c| {
                                c.is_ascii_alphanumeric() || matches!(c, '_' | '-' | '.')
                            })
                            .take(MAX_KEY_NAME)
                            .count();
                        let head = l[..kstart - before_len].trim_end();
                        let after_op = ["!==", "===", "!=", "=="]
                            .iter()
                            .find_map(|op| head.strip_suffix(op));
                        if let Some(lit) = after_op.map(str::trim_end) {
                            if let Some(q) =
                                lit.chars().last().filter(|c| matches!(c, '"' | '\'' | '`'))
                            {
                                let inner = &lit[..lit.len() - 1];
                                if let Some(open) = inner.rfind(q) {
                                    let literal = &inner[open + 1..];
                                    if accept(literal, true, Form::Compare) {
                                        let vstart =
                                            literal.as_ptr() as usize - text.as_ptr() as usize;
                                        push(
                                            hits,
                                            "credential with its value",
                                            vstart,
                                            vstart + literal.len(),
                                            decoded,
                                        );
                                        break;
                                    }
                                }
                            }
                        }
                    }
                    let rest = after[ident_rest.len()..]
                        .trim_start_matches([' ', '"', '\'', '`', ']', ')']);
                    let operator = after_operator(rest);
                    let value = operator.map(|(v, _)| v);
                    let form = operator.map(|(_, f)| f).unwrap_or(Form::Plain);
                    if value.is_none() {
                        if let Some(after_tag) = rest.strip_prefix('>') {
                            // `<apiToken>value</apiToken>`, or the value on the next line
                            let inline = after_tag.split('<').next().unwrap_or("").trim();
                            let next = all
                                .get(li + 1)
                                .map(|n| {
                                    n.trim_end_matches(['\n', '\r'])
                                        .split('<')
                                        .next()
                                        .unwrap_or("")
                                        .trim()
                                })
                                .unwrap_or("");
                            let cand = if inline.is_empty() { next } else { inline };
                            if !cand.is_empty() && accept(cand, false, Form::Plain) {
                                let cstart = cand.as_ptr() as usize - text.as_ptr() as usize;
                                push(
                                    hits,
                                    "credential with its value",
                                    cstart,
                                    cstart + cand.len(),
                                    decoded,
                                );
                                break;
                            }
                        }
                    }
                    if value.is_none() && !rest.is_empty() && !is_provider && !is_key_suffix {
                        // "api key 9f8e7d6c...": a keyword followed directly by a long random token
                        let token = rest.split_whitespace().next().unwrap_or("");
                        if token.len() >= 20
                            && entropy(token) >= 3.3
                            && token.chars().any(|c| c.is_ascii_digit())
                            && token.chars().any(|c| c.is_ascii_alphabetic())
                            && token.chars().all(|c| {
                                c.is_ascii_alphanumeric()
                                    || matches!(c, '+' | '/' | '_' | '-' | '=')
                            })
                        {
                            let vstart = offset + (l.len() - rest.len());
                            push(
                                hits,
                                "credential with its value",
                                vstart,
                                vstart + token.len(),
                                decoded,
                            );
                            break;
                        }
                    }
                    if let Some(v) = value {
                        let (token, quoted) = take_value(v.trim_start());
                        // `x == y` is code; `x == "literal"` is a credential written into a check
                        if (rest.starts_with("==") || rest.starts_with("!=")) && !quoted {
                            continue;
                        }
                        if accept(token, quoted, form) {
                            // the value itself, without its quotes
                            let vstart = token.as_ptr() as usize - text.as_ptr() as usize;
                            push(
                                hits,
                                "credential with its value",
                                vstart,
                                vstart + token.len(),
                                decoded,
                            );
                            break;
                        }
                    }
                }
            }
        }
        offset += line.len();
    }
}

/// "key 4f9a8c7e...": the bare word `key` counts only when a long random token follows it directly.
fn scan_bare_key(text: &str, decoded: bool, hits: &mut Vec<Hit>) {
    let lower = text.to_ascii_lowercase();
    let mut from = 0;
    while let Some(i) = lower[from..].find("key ") {
        let at = from + i;
        from = at + 4;
        if !is_word_boundary(text, at) {
            continue;
        }
        let token = text[at + 4..].split_whitespace().next().unwrap_or("");
        let token = token.trim_matches(|c| c == '"' || c == '\'' || c == ',' || c == '.');
        if token.len() >= 20
            && entropy(token) >= 3.3
            && token.chars().any(|c| c.is_ascii_digit())
            && token.chars().any(|c| c.is_ascii_alphabetic())
            && token
                .chars()
                .all(|c| c.is_ascii_alphanumeric() || matches!(c, '+' | '/' | '_' | '-' | '='))
        {
            push(
                hits,
                "credential with its value",
                at + 4,
                at + 4 + token.len(),
                decoded,
            );
        }
    }
}

fn scan_wallets(text: &str, decoded: bool, hits: &mut Vec<Hit>) {
    // a Solana-style keypair: a bracketed list of exactly 64 byte values
    let mut from = 0;
    while let Some(i) = text[from..].find('[') {
        let start = from + i;
        let Some(j) = text[start..].find(']') else {
            break;
        };
        let inner = &text[start + 1..start + j];
        let nums: Vec<&str> = inner.split(',').map(str::trim).collect();
        if nums.len() == 64 && nums.iter().all(|n| n.parse::<u16>().is_ok_and(|v| v < 256)) {
            push(hits, "solana keypair", start, start + j + 1, decoded);
        }
        from = start + 1;
    }
    // a 64-hex key next to a key-like name
    let lower = text.to_ascii_lowercase();
    for kw in [
        "private_key",
        "privatekey",
        "secret_key",
        "secretkey",
        "seed",
        "signing_key",
    ] {
        let mut f = 0;
        while let Some(i) = lower[f..].find(kw) {
            let after = &text[f + i + kw.len()..];
            f = f + i + kw.len();
            let raw = after.trim_start_matches([' ', '"', '\'', '=', ':']);
            let raw = raw.strip_prefix("0x").unwrap_or(raw);
            let hexrun: String = raw.chars().take_while(|c| c.is_ascii_hexdigit()).collect();
            if hexrun.len() == 64 {
                push(hits, "64-hex private key", f, f + hexrun.len(), decoded);
            }
        }
    }
    // a recovery phrase: 12 or 24 plain lowercase words after a phrase-like name
    for kw in [
        "seed phrase",
        "recovery phrase",
        "mnemonic",
        "secret phrase",
        "backup phrase",
    ] {
        let mut f = 0;
        while let Some(i) = lower[f..].find(kw) {
            let after =
                text[f + i + kw.len()..].trim_start_matches([' ', ':', '=', '"', '\'', '-']);
            f = f + i + kw.len();
            let line = after.lines().next().unwrap_or("");
            let words: Vec<&str> = line.split_whitespace().take(24).collect();
            let plain = words
                .iter()
                .take_while(|w| {
                    w.len() >= 3 && w.len() <= 8 && w.chars().all(|c| c.is_ascii_lowercase())
                })
                .count();
            // No embedded word list yet: ordinary sentences are told apart by repeated words and common function words.
            let phrase = &words[..plain.min(words.len())];
            const COMMON: &[&str] = &[
                "the", "and", "over", "with", "that", "this", "for", "are", "was", "were", "you",
                "your", "not", "but", "have", "from", "will", "all", "can",
            ];
            let distinct: std::collections::BTreeSet<&&str> = phrase.iter().collect();
            if distinct.len() != phrase.len()
                || phrase.iter().filter(|w| COMMON.contains(w)).count() >= 2
            {
                continue;
            }
            if plain == 12 || plain == 15 || plain == 18 || plain == 21 || plain == 24 {
                push(hits, "recovery phrase", f, f + line.len(), decoded);
            }
        }
    }
}

/// Shapes with a fixed layout but no prefix to search for: a Telegram bot token (`123456789:A` and 34 more characters)
/// and an Azure AD client secret (`...<digit>Q~` and 31 to 34 more characters).
fn scan_shapes(text: &str, decoded: bool, hits: &mut Vec<Hit>) {
    let bytes = text.as_bytes();
    let tail_ok = |c: u8| c.is_ascii_alphanumeric() || c == b'_' || c == b'-';
    let mut i = 0;
    while i < bytes.len() {
        if bytes[i] == b':' {
            let mut d = i;
            while d > 0 && bytes[d - 1].is_ascii_digit() {
                d -= 1;
            }
            let digits = i - d;
            let boundary =
                d == 0 || !(bytes[d - 1].is_ascii_alphanumeric() || bytes[d - 1] == b'_');
            if (5..=16).contains(&digits)
                && boundary
                && bytes.get(i + 1) == Some(&b'A')
                && bytes.len() >= i + 36
                && bytes[i + 2..i + 36].iter().all(|c| tail_ok(*c))
                && !bytes.get(i + 36).is_some_and(|c| tail_ok(*c))
                && !placeholder_body(&text[i + 2..i + 36])
            {
                push(hits, "telegram bot token", d, i + 36, decoded);
            }
        }
        // Mailchimp: 32 hex characters, `-us`, and the data-centre number
        if bytes[i] == b'-'
            && bytes.get(i + 1) == Some(&b'u')
            && bytes.get(i + 2) == Some(&b's')
            && i >= 32
            && bytes[i - 32..i].iter().all(|c| c.is_ascii_hexdigit())
            && bytes.get(i + 3).is_some_and(|c| c.is_ascii_digit())
            && (i == 32 || !(bytes[i - 33].is_ascii_alphanumeric() || bytes[i - 33] == b'_'))
            && !bytes
                .get(i + 4)
                .is_some_and(|c| c.is_ascii_alphanumeric() && !c.is_ascii_digit())
        {
            let digits_end = if bytes.get(i + 4).is_some_and(|c| c.is_ascii_digit()) {
                i + 5
            } else {
                i + 4
            };
            if !placeholder_body(&text[i - 32..i]) {
                push(hits, "mailchimp api key", i - 32, digits_end, decoded);
            }
        }
        if bytes[i] == b'Q' && bytes.get(i + 1) == Some(&b'~') && i >= 4 {
            let lead_ok = bytes[i - 4..i - 1]
                .iter()
                .all(|c| c.is_ascii_alphanumeric() || matches!(c, b'_' | b'~' | b'.'))
                && bytes[i - 1].is_ascii_digit();
            let mut e = i + 2;
            while e < bytes.len()
                && (bytes[e].is_ascii_alphanumeric()
                    || matches!(bytes[e], b'_' | b'~' | b'.' | b'-'))
            {
                e += 1;
            }
            let n = e - (i + 2);
            let boundary =
                i == 4 || !(bytes[i - 5].is_ascii_alphanumeric() || bytes[i - 5] == b'_');
            if lead_ok
                && boundary
                && (31..=34).contains(&n)
                && entropy(&text[i - 4..e]) >= 3.0
                && !placeholder_body(&text[i + 2..e])
            {
                push(hits, "azure client secret", i - 4, e, decoded);
            }
        }
        i += 1;
    }
}

/// One shell argument: up to the closing quote when quoted, otherwise up to the next whitespace (so `${USER}:secret`
/// stays whole).
fn curl_argument(s: &str) -> &str {
    match s.chars().next() {
        Some(q @ ('"' | '\'')) => {
            let rest = &s[1..];
            &rest[..rest.find(q).unwrap_or(rest.len())]
        }
        _ => &s[..s.find(char::is_whitespace).unwrap_or(s.len())],
    }
}

/// Credentials typed into a curl command: `-u user:password` and `-H "Authorization: ..."`.
fn scan_curl(text: &str, decoded: bool, hits: &mut Vec<Hit>) {
    let lower = text.to_ascii_lowercase();
    let mut from = 0;
    while let Some(i) = lower[from..].find("curl") {
        let at = from + i;
        from = at + 4;
        if !is_word_boundary(text, at)
            || lower
                .as_bytes()
                .get(at + 4)
                .is_some_and(|c| c.is_ascii_alphanumeric())
        {
            continue;
        }
        // the command and its continuation lines, up to the next curl
        let mut end = (at + 1500).min(text.len());
        while !text.is_char_boundary(end) {
            end -= 1;
        }
        let stop = lower[at + 4..end]
            .find("curl")
            .map(|p| at + 4 + p)
            .unwrap_or(end);
        let cmd = &text[at..stop];
        let mut rest = cmd;
        while let Some(j) = rest.find(['-']) {
            let flag_at = &rest[j..];
            let preceded_by_space = j == 0 || rest.as_bytes()[j - 1].is_ascii_whitespace();
            rest = &rest[j + 1..];
            if !preceded_by_space {
                continue;
            }
            let (kind, after) = if let Some(a) = flag_at.strip_prefix("--user") {
                ('u', a)
            } else if let Some(a) = flag_at.strip_prefix("--header") {
                ('h', a)
            } else if let Some(a) = flag_at.strip_prefix("-u") {
                ('u', a)
            } else if let Some(a) = flag_at.strip_prefix("-H") {
                ('h', a)
            } else {
                continue;
            };
            let after = after.trim_start_matches(['=', ' ', '\t']);
            let value = curl_argument(after);
            let vstart = value.as_ptr() as usize - text.as_ptr() as usize;
            if kind == 'u' {
                if let Some((user, pw)) = value.split_once(':') {
                    if pw.is_empty()
                        && user.len() >= 8
                        && credential_value_with(user, true)
                        && !templated(user)
                    {
                        push(
                            hits,
                            "credential in a curl command",
                            vstart,
                            vstart + value.len(),
                            decoded,
                        );
                    }
                    let pw_shape_ok = !pw.contains(['|', '\\', '{', '}', '^'])
                        && !pw.contains(char::is_whitespace)
                        && !word_slug(pw);
                    let distinct: BTreeSet<char> = pw.chars().collect();
                    if pw_shape_ok
                        && pw.len() >= 3
                        && distinct.len() >= 3
                        && pw != user
                        && !templated(pw)
                        && !indirect_reference(pw)
                        && !placeholder(pw)
                        && !["password", "pass", "secret", "token"]
                            .contains(&pw.to_ascii_lowercase().as_str())
                    {
                        push(
                            hits,
                            "password in a curl command",
                            vstart,
                            vstart + value.len(),
                            decoded,
                        );
                    }
                }
            } else if let Some((name, val)) = value.split_once(':') {
                if name.trim().eq_ignore_ascii_case("authorization") {
                    let cred = val.trim();
                    let cred = ["Bearer ", "Basic ", "Token ", "bearer ", "basic ", "token "]
                        .iter()
                        .find_map(|p| cred.strip_prefix(p))
                        .unwrap_or(cred)
                        .trim();
                    if credential_value_with(cred, true) && !templated(cred) {
                        push(
                            hits,
                            "credential in a curl header",
                            vstart,
                            vstart + value.len(),
                            decoded,
                        );
                    }
                }
            }
        }
    }
}

/// Sidekiq Pro and Enterprise gems are fetched with a credential of two eight-character hex halves, kept in an
/// environment variable named after the vendor host.
fn scan_gem_credentials(text: &str, decoded: bool, hits: &mut Vec<Hit>) {
    for name in [
        "BUNDLE_ENTERPRISE__CONTRIBSYS__COM",
        "BUNDLE_GEMS__CONTRIBSYS__COM",
    ] {
        let mut from = 0;
        while let Some(i) = text[from..].find(name) {
            let after = from + i + name.len();
            from = after;
            let rest = &text[after..];
            let value = rest.trim_start_matches([' ', '=', ':', '"', '\'']);
            let v = value.as_bytes();
            if v.len() >= 17
                && v[..8].iter().all(|c| c.is_ascii_hexdigit())
                && v[8] == b':'
                && v[9..17].iter().all(|c| c.is_ascii_hexdigit())
                && !v.get(17).is_some_and(|c| c.is_ascii_alphanumeric())
                && !placeholder_body(&value[..17].replace(':', ""))
            {
                let vstart = value.as_ptr() as usize - text.as_ptr() as usize;
                push(hits, "gem server credential", vstart, vstart + 17, decoded);
            }
        }
    }
}

fn scan_text(text: &str, decoded: bool) -> Vec<Hit> {
    let mut hits = Vec::new();
    scan_formats(text, decoded, &mut hits);
    scan_blocks_and_urls(text, decoded, &mut hits);
    scan_assignments(text, decoded, &mut hits);
    scan_wallets(text, decoded, &mut hits);
    scan_shapes(text, decoded, &mut hits);
    scan_curl(text, decoded, &mut hits);
    scan_gem_credentials(text, decoded, &mut hits);
    hits
}

// ---- decoding (bounded) ----

fn b64_value(c: u8) -> Option<u8> {
    match c {
        b'A'..=b'Z' => Some(c - b'A'),
        b'a'..=b'z' => Some(c - b'a' + 26),
        b'0'..=b'9' => Some(c - b'0' + 52),
        b'+' | b'-' => Some(62),
        b'/' | b'_' => Some(63),
        _ => None,
    }
}

pub fn base64_decode(s: &str) -> Option<Vec<u8>> {
    let bytes: Vec<u8> = s.bytes().filter(|b| *b != b'=').collect();
    if bytes.is_empty() || bytes.len() % 4 == 1 {
        return None;
    }
    let mut out = Vec::with_capacity(bytes.len() * 3 / 4);
    let mut buf = 0u32;
    let mut bits = 0;
    for b in bytes {
        buf = (buf << 6) | b64_value(b)? as u32;
        bits += 6;
        if bits >= 8 {
            bits -= 8;
            out.push((buf >> bits) as u8);
            buf &= (1 << bits) - 1;
        }
    }
    Some(out)
}

pub fn hex_decode(s: &str) -> Option<Vec<u8>> {
    if !s.len().is_multiple_of(2) || !all_hex(s) {
        return None;
    }
    (0..s.len())
        .step_by(2)
        .map(|i| u8::from_str_radix(&s[i..i + 2], 16).ok())
        .collect()
}

/// Budget for decoding, so a decode bomb cannot make the scan slow.
const MAX_DECODE_DEPTH: usize = 2;
const MAX_DECODED_BYTES: usize = 256 * 1024;
const MAX_SEGMENTS: usize = 64;

fn candidate_segments(text: &str) -> Vec<(usize, usize)> {
    let mut out = Vec::new();
    let mut start = None;
    for (i, c) in text
        .char_indices()
        .chain(std::iter::once((text.len(), ' ')))
    {
        let ok = B64.contains(c) && c != '=';
        match (ok, start) {
            (true, None) => start = Some(i),
            (false, Some(s)) => {
                if i - s >= 24 {
                    out.push((s, i));
                }
                start = None;
            }
            _ => {}
        }
        if out.len() >= MAX_SEGMENTS * 4 {
            break;
        }
    }
    out
}

fn hex_val(c: u8) -> Option<u8> {
    (c as char).to_digit(16).map(|d| d as u8)
}

/// Percent-decoding of every `%XX`, including one at the very end of the text.
fn percent_unescape(tok: &str) -> Option<String> {
    let b = tok.as_bytes();
    let mut out = Vec::with_capacity(b.len());
    let mut i = 0;
    let mut changed = false;
    while i < b.len() {
        if b[i] == b'%' && i + 2 < b.len() {
            if let (Some(h), Some(l)) = (hex_val(b[i + 1]), hex_val(b[i + 2])) {
                out.push(h << 4 | l);
                i += 3;
                changed = true;
                continue;
            }
        }
        out.push(b[i]);
        i += 1;
    }
    if !changed {
        return None;
    }
    String::from_utf8(out).ok()
}

/// `\uXXXX`, `\\uXXXX` and `U+XXXX` escapes, with surrogate pairs.
fn unicode_unescape(tok: &str) -> Option<String> {
    let c: Vec<char> = tok.chars().collect();
    let mut out = String::new();
    let mut i = 0;
    let mut changed = false;
    let four = |at: usize| -> Option<u32> {
        let s: String = c.get(at..at + 4)?.iter().collect();
        if s.len() == 4 && s.chars().all(|x| x.is_ascii_hexdigit()) {
            u32::from_str_radix(&s, 16).ok()
        } else {
            None
        }
    };
    while i < c.len() {
        let mut at = None;
        if c[i] == '\\' {
            let mut j = i;
            while j < c.len() && c[j] == '\\' && j - i < 2 {
                j += 1;
            }
            if c.get(j) == Some(&'u') || c.get(j) == Some(&'U') {
                at = Some(j + 1);
            }
        } else if c[i] == 'U' && c.get(i + 1) == Some(&'+') {
            at = Some(i + 2);
        }
        if let Some(a) = at {
            if let Some(mut cp) = four(a) {
                let mut next = a + 4;
                if (0xD800..0xDC00).contains(&cp) {
                    // a high surrogate must be followed by an escaped low surrogate
                    let mut k = next;
                    while k < c.len() && c[k] == '\\' && k - next < 2 {
                        k += 1;
                    }
                    let low = if c.get(k) == Some(&'u') {
                        four(k + 1)
                    } else {
                        None
                    };
                    match low {
                        Some(lo) if (0xDC00..0xE000).contains(&lo) => {
                            cp = 0x10000 + ((cp - 0xD800) << 10) + (lo - 0xDC00);
                            next = k + 5;
                        }
                        _ => return None,
                    }
                }
                out.push(char::from_u32(cp)?);
                i = next;
                changed = true;
                // `U+0067 U+0068`: a single space between two such escapes belongs to the run
                if c[a - 2..a] == ['U', '+']
                    && c.get(i).is_some_and(|x| x.is_whitespace())
                    && c.get(i + 1) == Some(&'U')
                    && c.get(i + 2) == Some(&'+')
                {
                    i += 1;
                }
                continue;
            }
        }
        out.push(c[i]);
        i += 1;
    }
    changed.then_some(out)
}

/// Whitespace- and quote-delimited tokens that contain an escape worth decoding.
fn escaped_tokens(text: &str) -> Vec<(usize, usize)> {
    let mut out = Vec::new();
    let mut start = None;
    let b = text.as_bytes();
    for (i, ch) in text
        .char_indices()
        .chain(std::iter::once((text.len(), ' ')))
    {
        let delim = ch.is_whitespace() || matches!(ch, '"' | '\'' | '`' | '<' | '>');
        match (delim, start) {
            (false, None) => start = Some(i),
            (true, Some(s)) => {
                let tok = &b[s..i];
                let has_pct = tok
                    .windows(3)
                    .any(|w| w[0] == b'%' && hex_val(w[1]).is_some() && hex_val(w[2]).is_some());
                let has_uni = tok.windows(2).any(|w| w == b"\\u" || w == b"U+");
                if has_pct || has_uni {
                    out.push((s, i));
                }
                start = None;
            }
            _ => {}
        }
        if out.len() >= MAX_SEGMENTS * 4 {
            break;
        }
    }
    // a run of `U+XXXX` escapes separated by single spaces is one segment
    let mut merged: Vec<(usize, usize)> = Vec::new();
    for (s, e) in out {
        let is_u = text[s..e].starts_with("U+");
        if let Some(last) = merged.last_mut() {
            if is_u
                && text[last.0..last.1].starts_with("U+")
                && text[last.1..s].len() == 1
                && text[last.1..s].trim().is_empty()
            {
                last.1 = e;
                continue;
            }
        }
        merged.push((s, e));
    }
    merged
}

fn scan_decoded(text: &str, depth: usize, budget: &mut usize, hits: &mut Vec<Hit>) {
    if depth >= MAX_DECODE_DEPTH || *budget == 0 {
        return;
    }
    let mut escapes = 0;
    for (s, e) in escaped_tokens(text) {
        if escapes >= MAX_SEGMENTS || *budget == 0 {
            break;
        }
        let tok = &text[s..e];
        for decoder in [percent_unescape, unicode_unescape] {
            let Some(inner) = decoder(tok) else { continue };
            if inner.len() > *budget
                || !inner
                    .chars()
                    .all(|c| !c.is_control() || matches!(c, '\n' | '\t' | '\r'))
            {
                continue;
            }
            escapes += 1;
            *budget = budget.saturating_sub(inner.len());
            for h in scan_text(&inner, true) {
                hits.push(Hit {
                    rule: h.rule,
                    start: s,
                    end: e,
                    decoded: true,
                });
            }
            scan_decoded(&inner, depth + 1, budget, hits);
        }
    }
    let mut seen = 0;
    for (s, e) in candidate_segments(text) {
        if seen >= MAX_SEGMENTS || *budget == 0 {
            break;
        }
        let seg = &text[s..e];
        let decoded = base64_decode(seg).or_else(|| hex_decode(seg));
        let Some(bytes) = decoded else { continue };
        if bytes.len() > *budget {
            continue;
        }
        let Ok(inner) = String::from_utf8(bytes) else {
            continue;
        };
        if !inner
            .chars()
            .all(|c| !c.is_control() || c == '\n' || c == '\t' || c == '\r')
        {
            continue;
        }
        seen += 1;
        *budget = budget.saturating_sub(inner.len());
        for h in scan_text(&inner, true) {
            hits.push(Hit {
                rule: h.rule,
                start: s,
                end: e,
                decoded: true,
            });
        }
        // `user:password` pairs (HTTP basic auth, docker auth) are credentials once decoded
        if let Some((u, p)) = inner.split_once(':') {
            if !u.is_empty()
                && u.len() <= 64
                && u.chars()
                    .all(|c| c.is_ascii_alphanumeric() || matches!(c, '.' | '_' | '-' | '@'))
                && !p.contains(['{', '}', '"', '\'', ','])
                && credential_value(p)
                && inner.len() <= 200
                && !inner.contains('\n')
            {
                hits.push(Hit {
                    rule: "decoded user:password",
                    start: s,
                    end: e,
                    decoded: true,
                });
            }
        }
        scan_decoded(&inner, depth + 1, budget, hits);
    }
}

/// Every credential-shaped thing in `text`, including inside bounded base64 and hex segments.
pub fn scan(text: &str) -> Vec<Hit> {
    let mut hits = scan_text(text, false);
    let mut budget = MAX_DECODED_BYTES;
    scan_decoded(text, 0, &mut budget, &mut hits);
    hits.sort_by_key(|h| (h.start, h.end));
    hits.dedup_by(|a, b| a.rule == b.rule && a.start == b.start && a.end == b.end);
    hits
}

/// The first reason the text looks like it holds a secret, in the short plain form the product shows.
/// Which generation of the detector this is. Bump it whenever a rule is added, removed or changed, so stores that kept text under
/// an older detector are checked again with this one (kk-memory does that at open). A test in `tests/corpus.rs` fails when the
/// detector's answers over its corpus change and this number was not bumped.
pub const DETECTOR_VERSION: u32 = 1;

pub fn looks_secret(text: &str) -> Option<&'static str> {
    scan(text).first().map(|h| h.rule)
}

// ---- release egress: known withheld values in transformed forms ----

fn b64_encode(bytes: &[u8], url: bool, pad: bool) -> String {
    let alpha: &[u8; 64] = if url {
        b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_"
    } else {
        b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"
    };
    let mut out = String::new();
    for chunk in bytes.chunks(3) {
        let n = (chunk[0] as u32) << 16
            | (*chunk.get(1).unwrap_or(&0) as u32) << 8
            | *chunk.get(2).unwrap_or(&0) as u32;
        for i in 0..4 {
            if i <= chunk.len() {
                out.push(alpha[((n >> (18 - 6 * i)) & 63) as usize] as char);
            } else if pad {
                out.push('=');
            }
        }
    }
    out
}

fn percent_encode(s: &str) -> String {
    s.bytes()
        .map(|b| {
            if b.is_ascii_alphanumeric() || matches!(b, b'-' | b'_' | b'.' | b'~') {
                (b as char).to_string()
            } else {
                format!("%{b:02X}")
            }
        })
        .collect()
}

/// Forms a withheld value can take when something reproduces it: raw, base64 (three spellings), hex, percent-encoded and
/// reversed. Only values of at least `min_len` characters are expanded, to keep false matches out.
pub fn variants(value: &str, min_len: usize) -> BTreeSet<String> {
    let mut out = BTreeSet::new();
    let v = value.trim();
    if v.len() < min_len {
        return out;
    }
    out.insert(v.to_string());
    out.insert(b64_encode(v.as_bytes(), false, true));
    out.insert(b64_encode(v.as_bytes(), false, false));
    out.insert(b64_encode(v.as_bytes(), true, false));
    let hex: String = v.bytes().map(|b| format!("{b:02x}")).collect();
    out.insert(hex.to_ascii_uppercase());
    out.insert(hex);
    out.insert(percent_encode(v));
    out.insert(v.chars().rev().collect());
    out.remove("");
    out
}

/// The secret part of a credential-bearing value: for `scheme://user:password@host/...` the password and the
/// `user:password` pair. Hosts and user names are not secrets by themselves and are not returned, because ordinary
/// finding text names services and hosts.
pub fn pieces(value: &str, min_len: usize) -> BTreeSet<String> {
    let mut out = BTreeSet::new();
    if let Some(rest) = value.split("://").nth(1) {
        let authority = rest.split(['/', '?', '#']).next().unwrap_or("");
        if let Some((userinfo, _host)) = authority.rsplit_once('@') {
            if let Some((_user, password)) = userinfo.split_once(':') {
                if password.len() >= min_len {
                    out.insert(password.to_string());
                }
                if userinfo.len() >= min_len {
                    out.insert(userinfo.to_string());
                }
            }
        }
    }
    out
}
